export const IMAGE_CHARACTER_SHEET_SKILL = `
【角色/产品设定表 Skill】

目标是产出一组"同一个对象、不同角度或状态"的参考图，供后续所有镜头复用。

## 流程

1. 先用 t2i 生成一张**基准图**：正面、中性光、干净背景、全身或标准角度，尽量少遮挡。这张图是后面所有变体的唯一来源。
2. 等基准图真正生成成功（status=success）后，再用 i2i 逐张派生变体，每张的 sourceNodeIds 都挂**基准图**，不要挂上一张变体（否则误差会逐张累积）。
3. 变体的提示词只描述**变化的那一项**，其余写"保持一致"：
   - 角度："同一角色，转为四分之三侧面，其余保持一致"
   - 服装："同一角色，换成米色风衣，五官发型保持一致"
   - 状态："同一角色，衣服湿透、头发贴额，五官保持一致"

## 结构

- 基准图 → 各变体，是一对多的星形，不是链形。
- 一组设定表内的变体之间不连线。
- 每张变体的标题写清它是什么（"主角-四分之三侧""主角-风衣"），后续挂参考时才认得出。

## 常见错误

- 用 t2i 生成每个角度：角色会变成不同的人。
- 变体挂变体：三张之后就不像原角色了。
- 一次性把所有角度塞进一张提示词让模型画四宫格：单元格分辨率不足，作参考图时细节不够。真的要四宫格见分镜拼图 Skill。
`.trim();

export const IMAGE_STORYBOARD_SKILL = `
【分镜拼图 Skill】

分镜拼图是把多个镜头画在一张图里，用于快速预览节奏和构图，**不是**用来当参考图的。

## 规则

- 用 t2i，一张图一个宫格阵列（2x2 或 3x3），提示词里明确写"分为 N 格，每格一个镜头，格与格之间有细白边"。
- 逐格描述：第 1 格写什么、第 2 格写什么，按顺序编号，保持同一美术风格和同一角色描述。
- size 选宽高比接近正方形的选项（取值见 canvas_list_capabilities）。

## 用完之后

分镜拼图确认后，**不要**把它当作 i2v 的参考图或 flf2v 的首帧——宫格图会被模型当成一整张画面，生成结果会带着分割线动起来。

正确做法：按拼图确认的构图，为每个镜头单独用 t2i 或 i2i 生成一张完整的单幅图，再各自进入视频能力。分镜拼图节点与这些单幅图之间可以连线表示派生来源。
`.trim();
