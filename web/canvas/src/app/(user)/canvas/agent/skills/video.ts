export const VIDEO_MULTI_SHOT_SKILL = `
【多镜头 Skill】

广告片、MV、宣传片、短片这类需要多个镜头串起来的需求。

## 顺序

1. **先确认结构再生成媒体**：用 canvas_create_text_nodes 一次性把每个镜头的文字卡建出来（镜号、时长、画面内容、镜头运动、声音）。这一步不消耗生成额度，用户可以直接改。
2. 等用户确认镜头表。
3. 补视觉锚点：每个镜头需要的角色图、场景图，用 t2i/i2i 生成（见图片 Skill 和设定表 Skill）。同一角色跨镜头必须挂同一张基准图。
4. 逐镜头建视频能力节点，sourceNodeIds 挂该镜头对应的图和文字节点。
5. 需要统一画质时，最后给每个视频接 sr。
6. 全部镜头 success 后，用 **canvas_concat_videos** 按镜号顺序拼成一条成片交付。这是多镜头作品的收尾步骤，不要止步于一堆散片段。

拼接是 stream copy 不重编码，所以**各段分辨率和编码必须一致**。混用了不同模型或不同尺寸时会报错——先给它们统一过一遍 sr 超分（同一个 sr 模型、同一组参数）再拼。

## 结构约定

- 镜头文字节点之间**不连线**——它们是平级的，不是谁生成谁。
- 每个视频节点连它自己的镜头文字节点和它用到的图，不要连总剧本。
- 横向按镜号排列（x 递增），纵向按管线阶段排列（文字 → 图 → 视频 → 超分）。

## 一致性

跨镜头保持同一个角色/产品，靠的是**所有镜头挂同一批参考图**，不是靠提示词里重复描述外貌。提示词里只写"图片1 中的角色"，把身份交给参考图。

## 批次

多镜头很容易超出单轮 12 步。分批：先做完镜头 1-3 的完整链路交付，再做 4-6。每批结束时如实汇报哪些成功、哪些还在 loading。
`.trim();

export const VIDEO_CONTINUATION_SKILL = `
【连续镜头 / 续接 Skill】

用户要"接着上一段继续""一镜到底""延长"。

## 标准做法：尾帧接首帧

这是连贯性最好的接法，可以自主完成，不需要用户手动操作：

1. 用 **canvas_wait_generation** 等上一段视频落地（还在 loading 就截不到帧）。
2. 调用 **canvas_extract_video_frame**，nodeId 传上一段视频节点，at 传 "last"。它会截出尾帧、建好图片节点并自动连线，返回新节点的 nodeId。
3. 用 **flf2v 关键帧** 建下一段，sourceNodeIds 挂**这张尾帧图**（只挂 1 张 = 只约束首帧）。
4. 提示词写承接内容 + 反重放约束，例如"承接前一动作继续，镜头保持同一机位，不要重放已经发生的动作"。
5. 需要更长的链就重复 2-4，每一段都从**它自己的上一段**截尾帧。

## 备选：同参考图接力

上一段视频跨域取不到、编码浏览器解不了导致截帧失败时，退回这条：用与上一段**相同的参考图**加 **i2v**，提示词同样写承接 + 反重放。画面连贯性弱于尾帧接法，要如实告诉用户为什么退化。

## 硬约束

- 不要声称能读取视频语义内容或做帧级对齐——能做的只有取某一时刻的画面。
- 每一段必须等前一段真正 success 才能开始，严格串行，不能并行提交整条链。
- 续接链是真实派生关系：尾帧图连它的源视频，下一段视频连这张尾帧图；段3 连 段2，不要都连段1。
- 每段提示词都要带反重放约束，否则模型容易从头再演一遍。
- 反重放约束只写进这一次的请求，不要回写进用户的分镜文本节点。
`.trim();

export const VIDEO_EDITING_SKILL = `
【视频编辑 Skill】

用 **vace 视频编辑**。它按输入组合自动分流玩法，你只要给对输入：

- 1 个源视频，不挂参考图 → 整体重绘/换风格/调色（v2v）
- 1 个源视频 + 参考图（最多 5 张）→ 按参考图替换主体、产品、服装（rv2v）
- 2 个源视频 → 多源合成编辑（mv2v）

输入槽位：metadata.src_video 必填（1~2 个），metadata.src_ref_images 选填（最多 5 张）。

## 提示词

写**要改成什么**，以及**要保持什么不变**。两者都写，否则模型会连不该动的一起改：

- "把主体的外套换成图片1 中的红色夹克，人物动作、机位和背景保持不变"
- "整体改为夜景冷色调，画面内容和运动保持不变"

## 注意

- 源视频必须是画布上真实存在、已经生成成功的视频节点。
- 局部替换的效果取决于参考图质量：参考图要干净、主体清晰、和目标在视频里的角度接近。
- 改完如果画质下降，再接 sr 超分，不要在同一次编辑里既改内容又指望提分辨率。
`.trim();
