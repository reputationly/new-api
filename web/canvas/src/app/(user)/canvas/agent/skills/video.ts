export const VIDEO_SKILL = `
【视频 Skill】

## 能力选择决策树

先看手里有什么，再决定用哪个能力。**这几个能力的输入语义完全不同，选错会得到不是你要的东西。**

- 只有文字，没有任何画面 → **t2v 文生视频**。输入只有提示词；参数 size、seconds。
- 有 1~3 张图，想让它们的**主体/服装/道具/场景**出现在视频里，但不要求画面从某一帧开始 → **i2v 图生视频**。参考图是内容依据，不是首帧约束。产物**无语音**。
- 要**带语音**的视频，或参考素材不止图片（还有参考视频/参考音频） → **r2va 参考生视频**。最多 9 图 + 3 视频 + 3 音频，至少要有 1 张图或 1 个视频。它能指定画幅（i2v 不能）。
- 有一张图，要求视频**从这一帧开始**动 → **flf2v 关键帧**，挂 1 张图。
- 有两张图，要求**从第一张开始、到第二张结束** → **flf2v 关键帧**，按连线顺序挂 2 张（第一张是首帧，第二张是尾帧）。
- 有人物图 + 一段语音，要人物开口说这段话 → **s2v 数字人**。两个输入都必填。
- 已有视频，要放大分辨率或提高帧率 → **sr 视频超分**。参数 sr_ratio（1 = 只插帧不放大）、target_fps（留空用部署默认）。
- 已有视频，要改内容、换风格、替换主体 → **vace 视频编辑**，见视频编辑 Skill。
- 已有视频，要给它配上声音 → **v2a 视频配音**。产物是**配好音的视频**，不是音频文件。
- 多段视频要接成一条成片 → **canvas_concat_videos**（不是能力节点，是画布工具）。

两个最容易搞错的地方：

1. **i2v 不是"首帧动画"**。要首帧约束请用 flf2v。
2. **i2v 与 r2va 都吃参考图，但 i2v 出的视频没有语音，r2va 有**。要人物说话且不想用数字人（s2v 需要现成音频）时，用 r2va。

## 提示词写法

视频提示词要写**运动**，不是写静态画面：

1. 主体在做什么，动作怎么发展（起→承→止）。
2. 镜头怎么动：固定/推/拉/摇/跟/环绕，速度快慢。
3. 环境的动态：风、水、光影变化、人群。
4. 时长内的节奏：几秒内完成什么，不要塞超过时长能承载的信息。

一个 5 秒镜头只能讲一个动作。写了三件事，模型会全部压缩，结果是三件都没做完。

## 参数

- seconds：必须取自 canvas_list_capabilities 返回的 durations，不要写任意数字。
- size：同上取自 sizes。
- 提示词写不下时优先删修饰词，保留动作和镜头运动。

## 任务节奏

视频任务是异步的，提交后 status=loading。

- 提交后不要立刻用它当下游输入（比如马上接 sr）。用 **canvas_wait_generation** 等它 success 再接。
- 多个互不依赖的镜头可以同一轮并行提交，然后一次 canvas_wait_generation 传全部 nodeIds 一起等。
- 依赖上一个视频结果的（超分、配乐、续接、截帧）必须等前一个成功。
- status=stalled 表示轮询超时但任务仍在服务端跑，不要重复提交。
`.trim();

