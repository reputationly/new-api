package common

import "testing"

// 像素串 → 最近的 H3 具名宽高比。非具名的约分结果(26:15 之类)不能直接下发,必须落到具名值上。
func TestNearestH3AspectRatio(t *testing.T) {
	cases := []struct {
		name string
		w, h int
		want string
	}{
		{"竖版 1080x1920", 1080, 1920, "9:16"},
		{"横版 1920x1080", 1920, 1080, "16:9"},
		{"480P 16:9 的 832x480 不能约成 26:15", 832, 480, "16:9"},
		{"768P 16:9 的 1344x768 实际画幅 1.75", 1344, 768, "16:9"},
		{"方形", 1024, 1024, "1:1"},
		{"接近方形但偏竖", 1080, 1200, "1:1"},
		// ⚠ 原来是 1000×1500 期望 3:4。但 1000/1500 = 0.6667 **正好就是 2:3**,
		// 老断言能过只是因为当时表里还没有 2:3。放开到 11 个比例后它必须落到 2:3
		// (见下面那条),所以这里换成真正的 3:4 尺寸,保住"竖版 3:4"这条覆盖意图。
		{"竖版 3:4", 1080, 1440, "3:4"},
		{"超宽 21:9", 2560, 1080, "21:9"},
		// 本次放开到 11 个比例后的中间档:客户传像素串时也要能落到最近的具名值上,
		// 否则 h3ApplyCanvas 找不到比例就不推画布,档位词被丢掉、出片退回 768p 16:9。
		{"4:5 竖版", 1080, 1350, "4:5"},
		{"3:2 横版", 1440, 960, "3:2"},
		{"5:4 横版", 1280, 1024, "5:4"},
		{"2:3 竖版", 960, 1440, "2:3"},
		{"超窄 9:21", 672, 1536, "9:21"},
		{"非法宽度", 0, 100, ""},
		{"非法高度", 100, -1, ""},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			if got := NearestH3AspectRatio(tc.w, tc.h); got != tc.want {
				t.Fatalf("NearestH3AspectRatio(%d, %d) = %q, want %q", tc.w, tc.h, got, tc.want)
			}
		})
	}
}
