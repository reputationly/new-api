//   - **XINGSHEN2 是服务端一次性编译**：用户需求 + 素材 → H3 Prompt。
//     这正是聚合增强段在做的事。它在官方 skill 之外补了 shot-planning
//     与 video-experience 两套经验，注释里写明来自官方 Ref2VA 语料的直接
//     阅读与抽帧观察。
